"""
Descriptive statistics for multitask/huggingface_format/ (the per-dataset
DatasetDict.save_to_disk() chat-messages datasets built by build_hf_datasets.py).

Companion to multitask/token_stats.py, which measures the separate flat-text
pipeline (multitask/data/train_unified.jsonl + eval/*.jsonl); this measures
the reformatted chat-messages Arrow datasets instead, per dataset/per split.

Writes the raw numbers to multitask/huggingface_format/dataset_stats.json and
regenerates the auto-generated section of the project-root README.md (between
the BEGIN/END markers below) -- the rest of that README is hand-authored and
left untouched.

Run with: python -m multitask.hf_dataset_stats
"""
import json
import re
import sys
import warnings
from pathlib import Path

import numpy as np
import tiktoken
from datasets import load_from_disk

from multitask.schemas import PARAGRAPH_OF, SUBTASK_OF, TASKS

warnings.filterwarnings("ignore")

HF_DIR = Path(__file__).resolve().parent / "huggingface_format"
ROOT_README = Path(__file__).resolve().parents[1] / "README.md"
BEGIN_MARKER = "<!-- BEGIN: multitask dataset stats (auto-generated by multitask/hf_dataset_stats.py -- do not edit by hand) -->"
END_MARKER = "<!-- END: multitask dataset stats -->"

tk_enc = tiktoken.get_encoding("cl100k_base")

qw_tokenizer = None
qw_error = None
try:
    from transformers import AutoTokenizer
    import transformers
    transformers.logging.set_verbosity_error()
    qw_tokenizer = AutoTokenizer.from_pretrained("Qwen/Qwen3-4B")
except Exception as e:  # noqa: BLE001
    qw_error = f"{type(e).__name__}: {e}"

print(f"Qwen3-4B tokenizer: {'ready' if qw_tokenizer else 'UNAVAILABLE (' + str(qw_error) + ')'}", file=sys.stderr)


def messages_text(messages) -> str:
    return "\n".join(m["content"] for m in messages)


def _stats(lens):
    if not lens:
        return None
    a = np.array(lens)
    return {"n": int(a.size), "min": int(a.min()), "mean": round(float(a.mean()), 1),
            "median": float(np.median(a)), "p95": float(np.percentile(a, 95)),
            "p99": float(np.percentile(a, 99)), "max": int(a.max())}


def summarize_texts(texts):
    """Batch-encode all texts at once (tiktoken's encode_batch / a fast HF
    tokenizer's batched call) instead of one Python-level call per row --
    orders of magnitude faster on the 100k+ row datasets (medmcqa, pubmedqa)."""
    n = len(texts)
    tk_lens = [len(t) for t in tk_enc.encode_batch(texts, disallowed_special=())]
    qw_lens = None
    if qw_tokenizer is not None:
        qw_lens = [len(ids) for ids in qw_tokenizer(texts, add_special_tokens=False)["input_ids"]]
    return {"n": n, "tiktoken_cl100k": _stats(tk_lens), "qwen3_4b": _stats(qw_lens) if qw_lens is not None else None}


SPLIT_ORDER = ["train", "dev", "test"]


def main():
    report = {"qwen3_4b_available": qw_tokenizer is not None, "qwen3_4b_error": qw_error, "datasets": {}}

    for ds_dir in sorted(p for p in HF_DIR.iterdir() if p.is_dir()):
        dd = load_from_disk(str(ds_dir))
        task = None
        splits = {}
        for split in sorted(dd.keys(), key=lambda s: SPLIT_ORDER.index(s) if s in SPLIT_ORDER else 99):
            ds = dd[split]
            texts = [messages_text(m) for m in ds["messages"]]
            if task is None and len(ds) > 0:
                task = ds[0]["task"]
            splits[split] = summarize_texts(texts)
        report["datasets"][ds_dir.name] = {
            "task": task,
            "category": TASKS.get(task, {}).get("category", ""),
            "task_description": TASKS.get(task, {}).get("instruction", ""),
            "splits": splits,
        }
        summary = ", ".join(f"{split}={s['n']}" for split, s in splits.items())
        print(f"[stats] {ds_dir.name} ({task}): {summary}")

    (HF_DIR / "dataset_stats.json").write_text(json.dumps(report, indent=2))
    write_readme(report)
    print("Wrote multitask/huggingface_format/dataset_stats.json and updated README.md", file=sys.stderr)


# Example-granularity/build-engineering property (one example per document
# vs. split per-label like cohort_eligibility) -- orthogonal to the
# CATEGORIES/TASKS taxonomy in schemas.py, not meant to track it.
DOC_LEVEL_TASKS = {
    "ner_re_medication", "family_history", "medication_event", "sdoh_event",
    "concept_assertion_relation",
}
NO_TEST_SPLIT_DATASETS = set()


def _fmt_tk(s, key="mean"):
    if not s:
        return "-"
    tk = s.get("tiktoken_cl100k") or {}
    return f"{tk.get(key, '-')}"


def build_generated_block(report):
    lines = [
        "## `multitask/huggingface_format/` datasets",
        "",
        "One HuggingFace `datasets` `DatasetDict` per dataset (train/dev/test, "
        "whichever splits exist), saved via `DatasetDict.save_to_disk()`. Every "
        "dataset shares the same schema:",
        "",
        "```",
        '{"messages": [{"role": "system"|"user"|"assistant", "content": str}, ...],',
        ' "task": str, "category": str, "dataset": str, "id": str}',
        "```",
        "",
        "so `tokenizer.apply_chat_template()` can be applied directly. Built by "
        "`multitask/build_hf_datasets.py` (`python -m multitask.build_hf_datasets`), "
        "from the same per-task builders in `multitask/builders/` that also feed the "
        "separate merged flat-text pipeline (`multitask/build_unified_dataset.py`). "
        "Reload any dataset with:",
        "",
        "```python",
        "from datasets import load_from_disk",
        'ds = load_from_disk("multitask/huggingface_format/<name>")',
        "```",
        "",
        "Stats below (example counts, tiktoken `cl100k_base` token-length of the "
        "full rendered example -- min/median/mean/max, per split where that split "
        "exists) are generated by `multitask/hf_dataset_stats.py` "
        "(`python -m multitask.hf_dataset_stats`) -- see "
        "`multitask/huggingface_format/dataset_stats.json` for full per-split "
        "percentiles (p95/p99)" + (" and Qwen3-4B token counts" if report["qwen3_4b_available"] else "") + ".",
        "",
        "### Datasets",
        "",
    ]

    header = ["dataset", "category", "task tag", "description", "train", "dev", "test"]
    for split_name in SPLIT_ORDER:
        header += [f"tk_min ({split_name})", f"tk_median ({split_name})",
                    f"tk_mean ({split_name})", f"tk_max ({split_name})"]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "---|" * len(header))
    for name, d in report["datasets"].items():
        splits = d["splits"]
        row = [
            name, d["category"] or "-", d["task"] or "-", d["task_description"] or "-",
            str(splits["train"]["n"]) if "train" in splits else "-",
            str(splits["dev"]["n"]) if "dev" in splits else "-",
            str(splits["test"]["n"]) if "test" in splits else "-",
        ]
        for split_name in SPLIT_ORDER:
            s = splits.get(split_name)
            row += [_fmt_tk(s, "min"), _fmt_tk(s, "median"), _fmt_tk(s, "mean"), _fmt_tk(s, "max")]
        lines.append("| " + " | ".join(row) + " |")
    lines.append("")

    lines.append("### Tier A subtask-enrichment datasets (train-only, additive)")
    lines.append("")
    lines.append(
        "These are **not** part of the standard per-task evaluation set. Each "
        "one re-frames a subset of an existing IE dataset's own gold "
        "annotations into an easier training-only pipeline-stage sub-task "
        "(NER-only, RE-only, trigger-only, attribute-only) -- see "
        "[`design.md`](./design.md)'s \"Fixing doc-level training-data "
        "scarcity\" section. They carry **no dev/test split** and **no "
        "`run_eval.py` dispatch entry**, and are deliberately **excluded "
        "from `train_unified.jsonl`** -- include or exclude one for a "
        "training run by choosing whether to `concatenate_datasets()` its "
        "directory alongside its parent's:"
    )
    lines.append("")
    dataset_task = {name: d["task"] for name, d in report["datasets"].items()}
    parents = sorted({p for p in SUBTASK_OF.values()})
    for parent in parents:
        lines.append(f"- Subtasks of `{parent}`:")
        for name, task in dataset_task.items():
            if SUBTASK_OF.get(task) == parent:
                n_train = (report["datasets"][name]["splits"].get("train") or {}).get("n", "?")
                lines.append(f"  - `{name}` (`{task}`): {n_train} train examples")
    lines.append("")

    lines.append(
        "### Paragraph-window datasets (HF-only, additive, not scored by the "
        "doc-level pipeline)"
    )
    lines.append("")
    lines.append(
        "A distinct mechanism from the Tier A subtask-enrichment datasets above: "
        "instead of relabeling the same whole-note text, each example here is "
        "genuinely new -- one paragraph or section excerpted from a note (see "
        "[`design.md`](./design.md)'s paragraph-chunking section). Boundaries "
        "are blank lines for `ner_re_medication` (measured: splitting this way "
        "loses only ~0.24% of gold relations, ~9.7 non-empty paragraphs/doc) "
        "or ALL-CAPS section headers for `concept_assertion_relation` (that "
        "format has zero blank-line breaks; measured: 0.00% cross-section "
        "relation loss, ~7.1 non-empty sections/doc). **Both `train` and "
        "`test` splits are built** (per the "
        "\"prepare all\" data-prep instruction, for experimentation "
        "flexibility) but this dataset carries **no `run_eval.py` dispatch "
        "entry** and is **excluded from `train_unified.jsonl`** -- doc-level "
        "prediction/scoring remains the authoritative eval for its parent task; "
        "this is purely additive training signal today:"
    )
    lines.append("")
    for parent in sorted({p for p in PARAGRAPH_OF.values()}):
        lines.append(f"- Paragraph-window views of `{parent}`:")
        for name, task in dataset_task.items():
            if PARAGRAPH_OF.get(task) == parent:
                d = report["datasets"][name]
                n_train = (d["splits"].get("train") or {}).get("n", "?")
                n_test = (d["splits"].get("test") or {}).get("n", "?")
                lines.append(f"  - `{name}` (`{task}`): {n_train} train / {n_test} test examples")
    lines.append("")

    lines.append("### Known gaps / small training sets")
    lines.append("")
    lines.append(
        "Four tasks are built at **document level** (one example per note/patient, "
        "the full entity/relation/event set as target) rather than split into many "
        "single-label examples the way `cohort_eligibility` (2018_n2c2_track1) was. "
        "This makes their train sets far smaller than every other task in the "
        "collection:"
    )
    lines.append("")
    for name, d in report["datasets"].items():
        if d["task"] in DOC_LEVEL_TASKS:
            n_train = (d["splits"].get("train") or {}).get("n", "?")
            lines.append(f"- `{name}` (`{d['task']}`): {n_train} train examples")
    lines.append("")
    lines.append(
        "By comparison, `cohort_eligibility` (2018_n2c2_track1) was deliberately "
        "split per-criterion into 2,626 train examples from the same 202 patients, "
        "avoiding this problem -- a template that could be applied to the doc-level "
        "tasks above (e.g. one example per entity/event/relation) if their small "
        "train sets turn out to limit model quality."
    )
    lines.append("")
    lines.append(
        "`ner_re_medication` and `medication_event` now have Tier A "
        "subtask-enrichment datasets available (see [Tier A subtask-enrichment "
        "datasets](#tier-a-subtask-enrichment-datasets-train-only-additive) "
        "above) as an opt-in additive lever for this. `ner_re_medication` "
        "additionally has a [paragraph-window dataset](#paragraph-window-datasets-hf-only-additive-not-scored-by-the-doc-level-pipeline) "
        "that adds genuinely new (not relabeled) training text spans. "
        "`concept_assertion_relation` now has the same pair of levers -- Tier A "
        "subtasks plus a section-window dataset (boundaries are ALL-CAPS "
        "section headers rather than blank lines, since this format has none)."
    )
    lines.append("")
    if NO_TEST_SPLIT_DATASETS:
        lines.append(
            "Separately, `" + "`, `".join(sorted(NO_TEST_SPLIT_DATASETS)) + "` have no "
            "test split released locally -- `dev` stands in as the held-out eval split "
            "for both in `build_hf_datasets.py`/`build_unified_dataset.py`."
        )
    return lines


def write_readme(report):
    block = "\n".join(build_generated_block(report))
    generated = f"{BEGIN_MARKER}\n{block}\n{END_MARKER}"

    existing = ROOT_README.read_text() if ROOT_README.exists() else ""
    pattern = re.compile(re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER), re.S)
    if pattern.search(existing):
        new_content = pattern.sub(generated, existing)
    elif existing:
        new_content = existing.rstrip("\n") + "\n\n" + generated + "\n"
    else:
        new_content = generated + "\n"

    ROOT_README.write_text(new_content)


if __name__ == "__main__":
    main()
